"""Statement generator for MRNA Financial Services.

Generates:
1. Text summary for WhatsApp (instant delivery)
2. PDF statement for WhatsApp attachment (professional document)

Statement types: account, portfolio, loan, transaction, tax
"""
import os
import logging
from datetime import datetime, timezone
from fpdf import FPDF

logger = logging.getLogger("mrna.statement")

PDF_DIR = os.path.join(os.path.dirname(__file__), "statements")
os.makedirs(PDF_DIR, exist_ok=True)


