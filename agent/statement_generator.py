async def generate_account_summary(customer_id: str) -> str:
    from db.database import get_customer, get_customer_loans, get_customer_portfolios, get_customer_tickets
    cust = await get_customer(customer_id)
    if not cust:
        return "Customer not found."

    loans = await get_customer_loans(customer_id)
    portfolios = await get_customer_portfolios(customer_id)
    tickets = await get_customer_tickets(customer_id)

    active_loans = [l for l in loans if l.get("status") == "active"]
    total_outstanding = sum(float(l.get("outstanding", 0) or 0) for l in active_loans)
    total_invested = sum(float(p.get("total_invested", 0) or 0) for p in portfolios)
    total_current = sum(float(p.get("current_value", 0) or 0) for p in portfolios)
    open_tickets = [t for t in tickets if t.get("status") not in ("resolved", "closed")]

    lines = [
        f"*Account Statement - MRNA*",
        f"Date: {datetime.now().strftime('%d %b %Y')}",
        f"",
        f"*Customer:* {cust.get('name', 'N/A')}",
        f"*ID:* {customer_id} | *Segment:* {cust.get('segment', 'N/A')}",
        f"*KYC Status:* {cust.get('kyc_status', 'N/A')}",
        f"",
        f"*Loans ({len(active_loans)} active):*",
        f"  Total Outstanding: SAR {total_outstanding:,.0f}",
    ]
    for l in active_loans:
        lines.append(f"  - {l.get('type','').title()} ({l['id']}): SAR {float(l.get('outstanding',0) or 0):,.0f}")

    lines += [
        f"",
        f"*Investments ({len(portfolios)} portfolios):*",
        f"  Total Invested: SAR {total_invested:,.0f}",
        f"  Current Value: SAR {total_current:,.0f}",
        f"  P&L: SAR {total_current - total_invested:+,.0f}",
    ]
    for p in portfolios:
        val = float(p.get("current_value", 0) or 0)
        lines.append(f"  - {p.get('name', p['id'])}: SAR {val:,.0f}")

    if open_tickets:
        lines += [f"", f"*Open Tickets:* {len(open_tickets)}"]
        for t in open_tickets[:3]:
            lines.append(f"  - {t['id']}: {t.get('subject', 'N/A')}")

    lines += [f"", f"_Generated by MRNA on {datetime.now().strftime('%d %b %Y %H:%M')}_"]
    return "\n".join(lines)


async def generate_loan_summary(customer_id: str) -> str:
    from db.database import get_customer, get_customer_loans, get_payment_history, get_next_emi
    cust = await get_customer(customer_id)
    if not cust:
        return "Customer not found."

    loans = await get_customer_loans(customer_id)
    if not loans:
        return "No loans found."

    lines = [
        f"*Loan Statement - MRNA*",
        f"Date: {datetime.now().strftime('%d %b %Y')}",
        f"Customer: {cust.get('name', 'N/A')} ({customer_id})",
        f"",
    ]

    for loan in loans:
        lid = loan["id"]
        lines += [
            f"*{loan.get('type','').title()} Loan ({lid})*",
            f"  Status: {loan.get('status', 'N/A')}",
            f"  Principal: SAR {float(loan.get('principal', 0) or 0):,.0f}",
            f"  Outstanding: SAR {float(loan.get('outstanding', 0) or 0):,.0f}",
            f"  Rate: {loan.get('interest_rate', 'N/A')}%",
            f"  Tenure: {loan.get('tenure_months', 'N/A')} months",
        ]
        try:
            nxt = await get_next_emi(lid)
            if nxt:
                lines.append(f"  Next EMI: SAR {float(nxt.get('amount', 0) or 0):,.0f} on {str(nxt.get('due_date', 'N/A'))[:10]}")
        except Exception:
            pass

        try:
            payments = await get_payment_history(lid, limit=3)
            if payments:
                lines.append(f"  Recent payments:")
                for p in payments:
                    lines.append(f"    {str(p.get('due_date',''))[:10]}: SAR {float(p.get('amount',0) or 0):,.0f} [{p.get('status','N/A')}]")
        except Exception:
            pass
        lines.append("")

    lines.append(f"_Generated by MRNA on {datetime.now().strftime('%d %b %Y %H:%M')}_")
    return "\n".join(lines)


async def generate_portfolio_summary(customer_id: str) -> str:
    from db.database import (
        get_customer, get_customer_portfolios, get_holdings,
        get_sips, get_dividends
    )
    cust = await get_customer(customer_id)
    if not cust:
        return "Customer not found."

    portfolios = await get_customer_portfolios(customer_id)
    if not portfolios:
        return "No portfolios found."

    lines = [
        f"*Portfolio Statement - MRNA*",
        f"Date: {datetime.now().strftime('%d %b %Y')}",
        f"Customer: {cust.get('name', 'N/A')} ({customer_id})",
        f"",
    ]

    grand_invested = 0
    grand_current = 0

    for port in portfolios:
        pid = port["id"]
        invested = float(port.get("total_invested", 0) or 0)
        current = float(port.get("current_value", 0) or 0)
        grand_invested += invested
        grand_current += current
        pnl = current - invested
        pnl_pct = (pnl / invested * 100) if invested else 0

        lines += [
            f"*{port.get('name', pid)}* ({port.get('type', 'N/A')})",
            f"  Invested: SAR {invested:,.0f} | Current: SAR {current:,.0f}",
            f"  P&L: SAR {pnl:+,.0f} ({pnl_pct:+.1f}%)",
        ]

        try:
            holdings = await get_holdings(pid)
            if holdings:
                lines.append(f"  Holdings ({len(holdings)}):")
                for h in holdings:
                    units = float(h.get("units", 0) or 0)
                    nav = float(h.get("current_nav", 0) or 0)
                    val = units * nav
                    lines.append(f"    - {h.get('fund_name', h.get('fund_id', 'N/A'))}: {units:,.2f} units @ SAR {nav:,.2f} = SAR {val:,.0f}")
        except Exception:
            pass

        try:
            sips = await get_sips(pid)
            active_sips = [s for s in sips if s.get("status") == "active"]
            if active_sips:
                lines.append(f"  Active SIPs:")
                for s in active_sips:
                    lines.append(f"    - SAR {float(s.get('amount',0) or 0):,.0f}/month into {s.get('fund_name', s.get('fund_id', 'N/A'))}")
        except Exception:
            pass

        try:
            divs = await get_dividends(pid)
            if divs:
                total_div = sum(float(d.get("amount", 0) or 0) for d in divs)
                lines.append(f"  Dividends received: SAR {total_div:,.0f} ({len(divs)} payments)")
        except Exception:
            pass

        lines.append("")

    pnl_total = grand_current - grand_invested
    lines += [
        f"*Total Portfolio*",
        f"  Invested: SAR {grand_invested:,.0f}",
        f"  Current Value: SAR {grand_current:,.0f}",
        f"  Total P&L: SAR {pnl_total:+,.0f} ({(pnl_total/grand_invested*100) if grand_invested else 0:+.1f}%)",
        f"",
        f"_Generated by MRNA on {datetime.now().strftime('%d %b %Y %H:%M')}_",
    ]
    return "\n".join(lines)


async def generate_transaction_summary(customer_id: str) -> str:
    from db.database import get_customer, get_customer_portfolios, get_transactions
    cust = await get_customer(customer_id)
    if not cust:
        return "Customer not found."

    portfolios = await get_customer_portfolios(customer_id)
    if not portfolios:
        return "No portfolios found."

    lines = [
        f"*Transaction Statement - MRNA*",
        f"Date: {datetime.now().strftime('%d %b %Y')}",
        f"Customer: {cust.get('name', 'N/A')} ({customer_id})",
        f"",
    ]

    for port in portfolios:
        pid = port["id"]
        txns = await get_transactions(pid, limit=10)
        if not txns:
            continue
        lines.append(f"*{port.get('name', pid)}*:")
        for t in txns:
            amt = float(t.get("amount", 0) or 0)
            date = str(t.get("executed_at", ""))[:10]
            lines.append(f"  {date} | {t.get('type','N/A').upper()} | {t.get('fund_name', t.get('fund_id','N/A'))} | SAR {amt:,.0f} | {t.get('status','N/A')}")
        lines.append("")

    lines.append(f"_Generated by MRNA on {datetime.now().strftime('%d %b %Y %H:%M')}_")
    return "\n".join(lines)


async def generate_tax_summary(customer_id: str) -> str:
    from db.database import (
        get_customer, get_customer_portfolios, get_transactions,
        get_dividends, get_customer_loans
    )
    cust = await get_customer(customer_id)
    if not cust:
        return "Customer not found."

    portfolios = await get_customer_portfolios(customer_id)
    loans = await get_customer_loans(customer_id)

    total_dividends = 0
    total_gains = 0
    total_interest = 0

    for port in portfolios:
        divs = await get_dividends(port["id"])
        total_dividends += sum(float(d.get("amount", 0) or 0) for d in divs)
        txns = await get_transactions(port["id"])
        sells = [t for t in txns if t.get("type") in ("sell", "switch_out")]
        total_gains += sum(float(t.get("amount", 0) or 0) for t in sells)

    for loan in loans:
        total_interest += float(loan.get("interest_rate", 0) or 0) * float(loan.get("principal", 0) or 0) / 100

    lines = [
        f"*Tax Summary - MRNA*",
        f"Date: {datetime.now().strftime('%d %b %Y')}",
        f"Customer: {cust.get('name', 'N/A')} ({customer_id})",
        f"",
        f"*Income:*",
        f"  Dividends Received: SAR {total_dividends:,.0f}",
        f"  Realized Gains (sells): SAR {total_gains:,.0f}",
        f"",
        f"*Deductible:*",
        f"  Estimated Loan Interest: SAR {total_interest:,.0f}",
        f"",
        f"Note: This is an indicative summary. Consult your tax advisor for ZATCA compliance.",
        f"",
        f"_Generated by MRNA on {datetime.now().strftime('%d %b %Y %H:%M')}_",
    ]
    return "\n".join(lines)


